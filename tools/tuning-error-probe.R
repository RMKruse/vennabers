library(tune)
library(parsnip)
library(rsample)
library(yardstick)
library(workflows)
library(dplyr)
set.seed(19)
folds <- vfold_cv(mtcars, v=3)
wf <- workflow() |> add_formula(mpg ~ wt + hp) |> add_model(decision_tree(tree_depth=tune(), min_n=2) |> set_engine('rpart') |> set_mode('regression'))
res <- tune_grid(wf, resamples=folds, grid=tibble(tree_depth=1:3), metrics=metric_set(rmse), control=control_grid(save_pred=TRUE, allow_par=FALSE))
# Inject a partially missing main metric into otherwise actual tune results.
for (i in seq_along(res$.metrics)) {
  res$.metrics[[i]]$.estimate <- res$.metrics[[i]]$tree_depth
  res$.metrics[[i]]$.estimate[res$.metrics[[i]]$tree_depth == 1] <- if(i == 1) NA_real_ else 0
}
cat('PARTIAL MAIN METRIC: native aggregate and selection\n')
print(collect_metrics(res))
print(select_best(res, metric='rmse'))
stopifnot(select_best(res, metric='rmse')$tree_depth == 1)
# Public filtering removes candidate from future optimization input / selection.
eligible <- collect_metrics(res) |> filter(n==nrow(folds), is.finite(mean)) |> select(tree_depth)
strict <- filter_parameters(res, parameters=eligible)
stopifnot(select_best(strict, metric='rmse')$tree_depth == 2)
# Throwing auxiliary metric cannot discard valid primary metric under desired contract.
broken_aux <- new_numeric_metric(function(data, ...) stop('auxiliary calculation failed'), direction='minimize')
auxres <- tune_grid(wf, resamples=folds, grid=tibble(tree_depth=1:2), metrics=metric_set(rmse, broken_aux), control=control_grid(save_pred=TRUE, allow_par=FALSE))
cat('THROWING AUXILIARY: returned metric rows per resample\n')
print(lapply(auxres$.metrics, nrow))
print(collect_notes(auxres))
cat('Prediction rows preserved: ', vapply(auxres$.predictions, nrow, integer(1)), '\n')
stopifnot(all(!vapply(auxres$.metrics, tibble::is_tibble, logical(1))))
cat('PUBLIC BAYES ONE-ITERATION CONTINUATION\n')
params <- dials::parameters(dials::tree_depth(range=c(1L, 8L)))
continued <- tune_bayes(wf, resamples=folds, initial=strict, iter=1, param_info=params, metrics=metric_set(rmse), control=control_bayes(save_pred=TRUE, allow_par=FALSE, seed=91, save_gp_scoring=TRUE))
print(collect_metrics(continued))
stopifnot(inherits(continued, 'iteration_results'))
stopifnot(any(continued$.iter == 1L))
# The first GP is allowed to train only on previously filtered candidates.
gp_files <- list.files(tempdir(), pattern='^gp_candidates_.*RData$', full.names=TRUE)
stopifnot(length(gp_files) == 1L)
gp_env <- new.env()
load(gp_files[[1]], envir=gp_env)
cat('Saved GP training data\n')
print(gp_env$gp_fit$tr)
stopifnot(nrow(gp_env$gp_fit$tr) == 2L)
cat('INITIAL RESAMPLE IDENTITY IS NOT VALIDATED\n')
set.seed(182)
other_folds <- vfold_cv(mtcars, v=3)
stopifnot(!identical(folds$splits[[1]]$in_id, other_folds$splits[[1]]$in_id))
mixed <- tune_bayes(wf, resamples=other_folds, initial=strict, iter=1, param_info=params, metrics=metric_set(rmse), control=control_bayes(save_pred=TRUE, allow_par=FALSE, seed=91))
stopifnot(inherits(mixed, 'iteration_results'), any(mixed$.iter == 1L))
cat('Mismatched initial and continuation splits accepted by native call.\n')
