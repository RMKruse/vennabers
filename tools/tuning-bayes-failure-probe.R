library(tune)
library(parsnip)
library(rsample)
library(yardstick)
library(workflows)
library(dplyr)
# Register an isolated test engine through public parsnip extension functions.
probe_fit <- function(formula, data, tree_depth, ...) {
  y <- stats::model.response(stats::model.frame(formula, data))
  if (tree_depth >= 4 && !any(y == 33.9)) stop('intentional one-fold candidate failure')
  list(value=mean(y) + tree_depth / 10, tree_depth=tree_depth)
}
probe_predict <- function(object, new_data) rep(object$value, nrow(new_data))
set_model_engine('decision_tree', mode='regression', eng='strict_probe')
set_dependency('decision_tree', eng='strict_probe', pkg='stats')
set_model_arg('decision_tree', eng='strict_probe', parsnip='tree_depth', original='tree_depth', func=list(pkg='dials', fun='tree_depth'), has_submodel=FALSE)
set_fit('decision_tree', eng='strict_probe', mode='regression', value=list(interface='formula', protect=c('formula','data'), func=c(fun='probe_fit'), defaults=list()))
set_encoding('decision_tree', eng='strict_probe', mode='regression', options=list(predictor_indicators='none', compute_intercept=FALSE, remove_intercept=FALSE, allow_sparse_x=FALSE))
set_pred('decision_tree', eng='strict_probe', mode='regression', type='numeric', value=list(pre=NULL, post=NULL, func=c(fun='probe_predict'), args=list(object=quote(object$fit), new_data=quote(new_data))))
set.seed(91)
folds <- vfold_cv(mtcars, v=3)
w <- workflow() |> add_formula(mpg ~ wt + hp) |> add_model(decision_tree(tree_depth=tune()) |> set_engine('strict_probe') |> set_mode('regression'))
params <- dials::parameters(dials::tree_depth(range=c(1L,8L)))
initial <- tune_grid(w, resamples=folds, grid=tibble(tree_depth=1:3), metrics=metric_set(rmse), control=control_grid(save_pred=TRUE, allow_par=FALSE))
stopifnot(all(collect_metrics(initial)$n == 3L))
bad_run <- tune_bayes(w, resamples=folds, initial=initial, iter=1, param_info=params, metrics=metric_set(rmse), control=control_bayes(save_pred=TRUE, allow_par=FALSE, save_gp_scoring=TRUE, seed=91))
print(collect_metrics(bad_run))
print(collect_notes(bad_run))
bad_summary <- collect_metrics(bad_run) |> filter(.iter==1L)
stopifnot(nrow(bad_summary)==1L, bad_summary$n==2L, bad_summary$tree_depth >=4L)
# Use actual per-split coverage and primary metric validity, not aggregate-only n.
raw <- collect_metrics(bad_run, summarize=FALSE) |> filter(.metric=='rmse')
valid <- raw |> group_by(tree_depth) |> summarise(valid=n()==3L && n_distinct(id)==3L && setequal(id,folds$id) && all(is.finite(.estimate)), .groups='drop') |> filter(valid) |> select(tree_depth)
clean <- filter_parameters(bad_run, parameters=valid)
stopifnot(!any(collect_metrics(clean)$tree_depth==bad_summary$tree_depth))
stopifnot(identical(class(clean), class(bad_run)))
stopifnot(setequal(clean$id,folds$id))
stopifnot(all(vapply(seq_len(nrow(clean)), function(i) identical(clean$splits[[i]]$in_id, folds$splits[[match(clean$id[i],folds$id)]]$in_id), logical(1))))
# Public continuation from the filtered object; save GP to inspect its actual inputs.
again <- tune_bayes(w, resamples=folds, initial=clean, iter=1, param_info=params, metrics=metric_set(rmse), control=control_bayes(save_pred=TRUE, allow_par=FALSE, save_gp_scoring=TRUE, seed=102))
gp_files <- list.files(tempdir(), pattern='^gp_candidates_.*RData$', full.names=TRUE)
stopifnot(length(gp_files)==1L)
e <- new.env(); load(gp_files[[1]], envir=e)
cat('GP after filtering the failed candidate\n')
print(e$gp_fit$tr)
stopifnot(nrow(e$gp_fit$tr)==3L)
# GP encoding maps the declared integer range [1, 8] into [0, 1].
stopifnot(isTRUE(all.equal(sort(e$gp_fit$tr$tree_depth), c(0, 1/7, 2/7))))
stopifnot(setequal(again$id,folds$id))
stopifnot(all(vapply(seq_len(nrow(again)), function(i) identical(again$splits[[i]]$in_id, folds$splits[[match(again$id[i],folds$id)]]$in_id), logical(1))))
cat('PASS: failed candidate omitted from next GP; full planned split identities preserved.\n')
